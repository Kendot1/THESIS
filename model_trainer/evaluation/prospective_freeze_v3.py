"""Seal and preflight a new 7/4/1 prospective forecast package.

The seal binds model, selection, forecast-input snapshot, and typed forecasts.
It does not assert that the forecast CSV was actually generated by that model;
this requires reproducible replay and independent provenance review.
"""
import argparse
import json
from datetime import datetime, time, timedelta, timezone
from pathlib import Path

import pandas as pd

from data.snapshot import MANIFEST_FILE, read_snapshot
from data.preprocessor import DataPreprocessor, SERIES_KEY
from evaluation.frozen_holdout import PHILIPPINE_TIME, calendar_date, csv_rows, digest, relative_file
from evaluation.prospective_horizons_v3 import (
    CLOSED_HOLDOUT_START, SCHEMA_VERSION, STEPS, TARGET_DEFINITION,
    _timestamp, _validated_forecast_rows, load_contract, target_bounds,
)
from evaluation.prospective_validation_v3 import compare_validation
from models.model_store import HASHED_REQUIRED_FILES, SOURCE_SNAPSHOT_FILES

POLICY_VERSION = 12
ACCEPTANCE_CRITERIA = {
    "minimum_prospective_origins": 3,
    "minimum_interval_rows_per_horizon": 30,
    "minimum_product_interval_validation_periods": 20,
    "minimum_product_interval_validation_origins": 20,
    "minimum_interval_coverage_80_pct": 75.0,
    "minimum_interval_coverage_95_pct": 90.0,
    "minimum_product_interval_coverage_80_pct": 70.0,
    "minimum_product_interval_coverage_95_pct": 85.0,
    "maximum_product_error_deterioration_pct": 10.0,
    "maximum_daily_lead_error_deterioration_pct": 10.0,
    "per_horizon_max_mae_php": 5.0,
    "per_horizon_max_rmse_php": 5.0,
    "per_horizon_max_mape_pct": 5.0,
    "strict_less_than_horizon_targets": True,
}
SELECTION_FILE = "selection.json"
FORECAST_FILE = "forecasts.csv"
CONTRACT_FILE = "contract.json"
EVALUATION_CODE_FILES = (
    "prospective_horizons_v3.py", "prospective_validation_v3.py",
    "prospective_freeze_v3.py", "prospective_admission_v3.py",
    "prospective_promotion_v3.py",
)


def _read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def _evaluation_code_hashes():
    root = Path(__file__).resolve().parent
    return {name: digest((root / name).read_bytes()) for name in EVALUATION_CODE_FILES}


def _model_digests(run_dir):
    metadata_path = run_dir / "metadata.json"
    metadata = _read_json(metadata_path)
    if metadata.get("run_id") != run_dir.name:
        raise ValueError("Model metadata names another run")
    expected = metadata.get("sha256", {})
    required = HASHED_REQUIRED_FILES | SOURCE_SNAPSHOT_FILES
    if not required.issubset(expected):
        raise ValueError("Candidate bundle lacks complete hashed model/source artifacts")
    for name, hash_value in expected.items():
        if digest((run_dir / name).read_bytes()) != hash_value:
            raise ValueError(f"Candidate bundle hash mismatch: {name}")
    return metadata, digest(metadata_path.read_bytes()), expected


def _validation_scope(evidence_dir, selection, selection_origin, selected_at):
    """Preflight a label-free key manifest before opening validation outcomes."""
    scope_path = relative_file(evidence_dir, selection["validation_scope_file"])
    scope_bytes = scope_path.read_bytes()
    if digest(scope_bytes) != selection["validation_scope_sha256"]:
        raise ValueError("Validation scope-manifest SHA-256 mismatch")
    scope = _read_json(scope_path)
    declared = selection["declared_series"]
    origins = selection["validation_origins"]
    if (not isinstance(origins, list) or len(origins) < 3
            or origins != sorted(set(origins))):
        raise ValueError("Selection must predeclare at least three sorted validation origins")
    parsed_origins = [calendar_date(value) for value in origins]
    if (scope.get("schema_version") != 1
            or scope.get("forecast_file") != selection["validation_forecasts_file"]
            or scope.get("forecast_sha256") != selection["validation_forecasts_sha256"]
            or scope.get("declared_series") != declared
            or scope.get("origins") != origins):
        raise ValueError("Validation scope manifest differs from the selection record")
    key_rows = scope.get("forecast_keys")
    if not isinstance(key_rows, list):
        raise ValueError("Validation scope manifest requires its canonical forecast-key list")
    seen = set()
    expected = set()
    for series in declared:
        for origin in parsed_origins:
            if origin >= selection_origin:
                raise ValueError("Validation origin must precede the selected forecast origin")
            for horizon, count in STEPS.items():
                for step in range(1, count + 1):
                    start, end = target_bounds(origin, horizon, step)
                    if (end >= selected_at.astimezone(PHILIPPINE_TIME).date()
                            or end >= CLOSED_HOLDOUT_START):
                        raise ValueError("Validation scope overlaps selection or closed holdout")
                    expected.add((series, origin.isoformat(), horizon, step,
                                 start.isoformat(), end.isoformat()))
    for item in key_rows:
        if not isinstance(item, dict):
            raise ValueError("Validation scope key must be an object")
        try:
            series = item["series"]
            origin = calendar_date(item["origin"])
            horizon = item["forecast_horizon"]
            step = item["forecast_step"]
            start = calendar_date(item["target_period_start"])
            end = calendar_date(item["target_period_end"])
        except (KeyError, TypeError) as exc:
            raise ValueError("Validation scope key has missing or invalid fields") from exc
        key = (series, origin.isoformat(), horizon, step, start.isoformat(), end.isoformat())
        if key in seen:
            raise ValueError("Duplicate validation scope key")
        seen.add(key)
        if key not in expected:
            raise ValueError("Validation scope contains a noncanonical or ineligible key")
    if seen != expected:
        raise ValueError("Validation scope does not cover the complete predeclared key mask")
    return scope


def _selection(evidence_dir, run_dir, metadata, metadata_sha, now):
    path = evidence_dir / SELECTION_FILE
    selection = _read_json(path)
    if (selection.get("schema_version") != SCHEMA_VERSION
            or selection.get("promotion_policy_version") != POLICY_VERSION
            or selection.get("model_run_id") != run_dir.name
            or selection.get("model_metadata_sha256") != metadata_sha
            or selection.get("acceptance_criteria") != ACCEPTANCE_CRITERIA):
        raise ValueError("Selection is not bound to schema-v3 Policy 12 and the candidate bundle")
    selected_at = _timestamp(selection["selected_at"])
    created_at = _timestamp(metadata["created_at"])
    if not created_at <= selected_at <= now:
        raise ValueError("Model creation and selection chronology is invalid")
    origin = calendar_date(selection["forecast_origin"])
    deadline = datetime.combine(origin + timedelta(days=1), time.min, PHILIPPINE_TIME)
    if now >= deadline:
        raise ValueError("Cannot seal after the first target day")
    declared = selection["declared_series"]
    if (not isinstance(declared, list) or not declared
            or len(set(declared)) != len(declared)):
        raise ValueError("Selection must declare a unique nonempty series scope")
    excluded = selection.get("excluded_series", [])
    if (not isinstance(excluded, list)
            or any(not isinstance(item, dict)
                   or not str(item.get("reason", "")).strip()
                   or not isinstance(item.get("series"), str) for item in excluded)
            or len({item["series"] for item in excluded}) != len(excluded)
            or set(declared) & {item["series"] for item in excluded}):
        raise ValueError("Excluded input series require unique identities and reasons")
    _validation_scope(evidence_dir, selection, origin, selected_at)
    validation_path = relative_file(evidence_dir, selection["validation_forecasts_file"])
    if digest(validation_path.read_bytes()) != selection["validation_forecasts_sha256"]:
        raise ValueError("Validation forecast hash differs from selection")
    compare_validation(validation_path, selection)
    return selection, path, origin


def _input_snapshot(evidence_dir, origin, now):
    frame, manifest = read_snapshot(evidence_dir)
    captured = _timestamp(manifest["captured_at_utc"])
    if captured > now:
        raise ValueError("Forecast input snapshot is dated after the freeze")
    dates = pd.to_datetime(frame["report_date"], errors="coerce")
    if dates.isna().any() or dates.max().date() > origin:
        raise ValueError("Forecast input snapshot contains invalid or future observations")
    if calendar_date(manifest["report_date_max"]) != dates.max().date():
        raise ValueError("Forecast input snapshot date range differs from its manifest")
    clean = DataPreprocessor().validate(frame, apply_source_quality_exclusions=False)
    identities = {"||".join(key) for key in clean[SERIES_KEY]
                  .drop_duplicates().itertuples(index=False, name=None)}
    if not identities:
        raise ValueError("Forecast input snapshot has no valid series")
    return manifest, identities


def _check_population(selection, input_series):
    declared = set(selection["declared_series"])
    excluded = {item["series"] for item in selection.get("excluded_series", [])}
    if declared | excluded != input_series:
        raise ValueError("Selected and excluded series do not cover the forecast input scope")


def seal(evidence_dir, run_dir):
    """Create contract.json exactly once after checking pre-target inputs."""
    evidence_dir, run_dir = Path(evidence_dir), Path(run_dir)
    now = datetime.now(timezone.utc)
    if (evidence_dir / CONTRACT_FILE).exists():
        raise FileExistsError("A prospective contract is already sealed")
    metadata, metadata_sha, hashes = _model_digests(run_dir)
    selection, selection_path, origin = _selection(
        evidence_dir, run_dir, metadata, metadata_sha, now)
    source, input_series = _input_snapshot(evidence_dir, origin, now)
    _check_population(selection, input_series)
    forecast_bytes = (evidence_dir / FORECAST_FILE).read_bytes()
    status_counts = {status: 0 for status in ("active", "fallback", "missing")}
    for row in csv_rows(forecast_bytes, {"prediction_status"}):
        status = row["prediction_status"].strip().lower()
        if status not in status_counts:
            raise ValueError("Forecast has an unknown prediction_status")
        status_counts[status] += 1
    contract = {
        "schema_version": SCHEMA_VERSION,
        "target_definition": TARGET_DEFINITION,
        "holdout_type": "prospective",
        "model_run_id": run_dir.name,
        "forecast_origin": origin.isoformat(),
        "forecasts_frozen_at_utc": now.astimezone(timezone.utc).isoformat(),
        "declared_series": selection["declared_series"],
        "excluded_series": selection.get("excluded_series", []),
        "total_input_series": len(input_series),
        "forecast_file": FORECAST_FILE,
        "forecast_sha256": digest(forecast_bytes),
        "forecast_rows": len(selection["declared_series"]) * 12,
        "prediction_status_counts": status_counts,
        "selection_file": SELECTION_FILE,
        "selection_sha256": digest(selection_path.read_bytes()),
        "model_metadata_sha256": metadata_sha,
        "model_bundle_sha256": hashes,
        "evaluation_code_sha256": _evaluation_code_hashes(),
        "forecast_input_snapshot_sha256": source["sha256"],
        "forecast_input_manifest_sha256": digest((evidence_dir / MANIFEST_FILE).read_bytes()),
        "forecast_input_last_report_date": source["report_date_max"],
    }
    _validated_forecast_rows(contract, forecast_bytes)
    path = evidence_dir / CONTRACT_FILE
    with path.open("x", encoding="utf-8") as stream:
        json.dump(contract, stream, indent=2, sort_keys=True)
        stream.write("\n")
    return verify_seal(path, run_dir)


def verify_seal(contract_path, run_dir):
    """Revalidate all pre-outcome evidence without opening any actuals."""
    contract_path, run_dir = Path(contract_path), Path(run_dir)
    contract, _, integrity = load_contract(contract_path)
    evidence_dir = contract_path.parent
    if contract.get("model_run_id") != run_dir.name:
        raise ValueError("Contract belongs to another model")
    metadata, metadata_sha, hashes = _model_digests(run_dir)
    if contract.get("evaluation_code_sha256") != _evaluation_code_hashes():
        raise ValueError("Version-3 evaluation code differs from the sealed contract")
    if (contract.get("model_metadata_sha256") != metadata_sha
            or contract.get("model_bundle_sha256") != hashes):
        raise ValueError("Frozen contract does not match the candidate model bundle")
    selection_path = relative_file(evidence_dir, contract["selection_file"])
    if (selection_path.name != SELECTION_FILE
            or digest(selection_path.read_bytes()) != contract["selection_sha256"]):
        raise ValueError("Selection record differs from frozen contract")
    frozen_at = _timestamp(contract["forecasts_frozen_at_utc"])
    selection, _, origin = _selection(
        evidence_dir, run_dir, metadata, metadata_sha, frozen_at)
    if (origin.isoformat() != contract["forecast_origin"]
            or selection["declared_series"] != contract["declared_series"]):
        raise ValueError("Selection and frozen target population differ")
    source, input_series = _input_snapshot(evidence_dir, origin, frozen_at)
    _check_population(selection, input_series)
    if (contract.get("excluded_series") != selection.get("excluded_series", [])
            or contract.get("total_input_series") != len(input_series)):
        raise ValueError("Frozen input series scope differs from selection")
    if (contract.get("forecast_input_snapshot_sha256") != source["sha256"]
            or contract.get("forecast_input_manifest_sha256")
                != digest((evidence_dir / MANIFEST_FILE).read_bytes())
            or contract.get("forecast_input_last_report_date") != source["report_date_max"]):
        raise ValueError("Forecast input snapshot differs from frozen contract")
    return {**integrity, "selection_sha256": contract["selection_sha256"],
            "model_metadata_sha256": metadata_sha,
            "forecast_input_snapshot_sha256": source["sha256"]}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("evidence_dir", type=Path)
    parser.add_argument("model_run_dir", type=Path)
    args = parser.parse_args(argv)
    print(json.dumps(seal(args.evidence_dir, args.model_run_dir), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
